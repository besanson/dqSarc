"""Single source of truth for experiment state (reviewer item #1).

Reads the ingested provenance in ``paper/data/<exp>/reference_summary.json`` (each written
from a committed ``results/<exp>-live`` branch by ``paper/scripts/ingest_results.py``) and
emits, from that one source:

  - ``reports/experiment_status.json``  — machine-readable manifest
  - ``EXPERIMENT_STATUS.md``            — human-readable table

Every other document (README, paper, FINDINGS, FIRING_PLAN) should reference this rather than
restate experiment state, so no reader ever has to wonder which results are current. Invalid
runs (first-wave + the cap-truncated h4) are recorded too, for transparency (reviewer item #11)
— they are retained on their branches and never ingested.

Run: ``python scripts/experiment_status.py`` (also wired as ``make status``).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "paper" / "data"

# Which paper section consumes each experiment's result.
PAPER_SECTION = {
    "h1-full": r"\S Results — H1 (Silence)",
    "h1-ladder": r"\S Results — H1 capability ladder (headline)",
    "h2-detection": r"\S Results — H2 (Detection asymmetry)",
    "h3-frontier": r"\S Results — H3 (Gating dominance)",
    "h4-recovery": r"\S Results — H4 (Downstream sufficiency)",
}
ORDER = ["h1-full", "h1-ladder", "h2-detection", "h3-frontier", "h4-recovery"]

# Invalid runs, retained on their branches for audit, never ingested (FINDINGS §6, §8).
INVALID = [
    ("h1-full (first wave)", "2993ece", "buggy sampler / naive-prompt era"),
    ("h2-detection (first wave)", "a37bf0b", "pre-fix loss, naive prompt, buggy sampler"),
    ("h3-frontier (first wave)", "0a6f545", "pre-fix loss, naive prompt, buggy sampler"),
    ("h4-recovery (first wave)", "5fc430f", "pre-fix loss, naive prompt, buggy sampler"),
    ("h1-ladder (first wave)", "e47f55e", "naive prompt, buggy sampler"),
    ("ablations (first wave)", "47c334d", "naive prompt, buggy sampler"),
    ("h4-recovery (cap-truncated)", "701c38e", "API spend cap truncated the run to 2/8 classes"),
]


def _load(exp: str) -> dict[str, Any] | None:
    p = DATA / exp / "reference_summary.json"
    if not p.exists():
        return None
    data: Any = json.loads(p.read_text())
    return data if isinstance(data, dict) else None


def build_manifest() -> dict[str, Any]:
    valid = []
    for exp in ORDER:
        d = _load(exp)
        if d is None:
            continue
        pv = d["provenance"]
        valid.append(
            {
                "experiment": exp,
                "branch": pv["branch"],
                "commit_sha": pv["sha"],
                "run_id": pv["run_id"],
                "prompt_variant": pv["prompt_variant"],
                "sampler": pv["sampling"],
                "loss_definition": "paired-counterfactual-v2",
                "config_hash": pv["config_hash"],
                "instrumentation": pv["instrumentation"],
                "spend_usd": pv["spend_usd"],
                "cells": pv["cells"],
                "validity": "VALID",
                "ingested": f"paper/data/{exp}/reference_summary.json",
                "paper_section": PAPER_SECTION.get(exp, ""),
                "verdict": d.get("verdict", ""),
            }
        )
    return {
        "generated_by": "scripts/experiment_status.py",
        "campaign": "corrected campaign on the cap-hardened harness (2026-07)",
        "valid_experiments": valid,
        "invalid_runs_retained_for_audit": [
            {"run": r, "commit_sha": s, "grounds": g} for r, s, g in INVALID
        ],
        "total_spend_usd_valid": round(sum(v["spend_usd"] for v in valid), 2),
    }


def render_md(m: dict[str, Any]) -> str:
    lines = [
        "# EXPERIMENT STATUS — single source of truth",
        "",
        "Auto-generated by `scripts/experiment_status.py` from the committed",
        "`results/<exp>-live` branches (via `paper/data/<exp>/reference_summary.json`).",
        "**Do not edit by hand.** Every other document references this file for experiment",
        "state; if this and another doc disagree, this file wins.",
        "",
        f"Campaign: {m['campaign']}. The rate-axis re-runs (h3-frontier, h4-recovery) and the",
        "ladder carry the cap-hardened instrumentation (`api-error-aware-v1`); h1-full and",
        "h2-detection ran on the corrected harness *before* that tag was added and were",
        "verified complete (all classes ran, no truncation). Per-run `instrumentation` is in",
        f"the table below. Total valid spend: **${m['total_spend_usd_valid']:.2f}**.",
        "",
        "## Valid experiments (current — these are the results the paper reports)",
        "",
        "| experiment | branch @ SHA | prompt | sampler | loss | config_hash | instrum. | spend "
        "| cells | validity | ingested | verdict |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for v in m["valid_experiments"]:
        instr = v.get("instrumentation") or "(pre-hardening)"
        lines.append(
            f"| `{v['experiment']}` | `{v['branch']}` @ `{v['commit_sha']}` "
            f"| {v['prompt_variant']} | {v['sampler']} | {v['loss_definition']} "
            f"| `{v['config_hash']}` | {instr} | ${v['spend_usd']:.2f} | {v['cells']} | "
            f"**{v['validity']}** | ✓ | {v['verdict']} |"
        )
    lines += [
        "",
        "## Invalid runs — retained on their branches for audit, never ingested",
        "",
        "Kept for full transparency (no historical data deleted); superseded by the valid",
        "runs above. See `reports/FINDINGS.md` §6 and §8.",
        "",
        "| run | commit_sha | grounds |",
        "|---|---|---|",
    ]
    for r in m["invalid_runs_retained_for_audit"]:
        lines.append(f"| {r['run']} | `{r['commit_sha']}` | {r['grounds']} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    m = build_manifest()
    (ROOT / "reports" / "experiment_status.json").write_text(
        json.dumps(m, indent=2) + "\n", encoding="utf-8"
    )
    (ROOT / "EXPERIMENT_STATUS.md").write_text(render_md(m), encoding="utf-8")
    nvalid = len(m["valid_experiments"])
    ninvalid = len(m["invalid_runs_retained_for_audit"])
    print(
        f"wrote EXPERIMENT_STATUS.md + reports/experiment_status.json "
        f"({nvalid} valid, {ninvalid} invalid)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
